-- ---------- tables ----------
create table if not exists public.store (
  id int primary key default 1 check (id = 1),
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  n text not null,
  ph text not null,
  ad text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  no text,
  created_at timestamptz not null default now(),
  d date not null default current_date,
  uid uuid references auth.users(id) on delete set null,
  n text, ph text, ad text, it text,
  items jsonb not null default '[]'::jsonb,
  t numeric not null default 0,
  s text not null default 'New'
);
create index if not exists orders_uid_idx on public.orders(uid);
create index if not exists orders_d_idx on public.orders(d);

insert into public.store (id, data) values (1, '{}'::jsonb) on conflict (id) do nothing;

-- ---------- admin helper functions ----------
create or replace function public.is_admin() returns boolean
language sql security definer set search_path = public stable
as $$ select exists (select 1 from public.admins where user_id = auth.uid()) $$;

create or replace function public.has_admin() returns boolean
language sql security definer set search_path = public stable
as $$ select exists (select 1 from public.admins) $$;

-- Prothom je admin account banay shei admin hoy. Tarpor ar keu admin hote pare na.
create or replace function public.claim_admin() returns boolean
language plpgsql security definer set search_path = public
as $$
begin
  if auth.uid() is null then return false; end if;
  perform pg_advisory_xact_lock(7001);
  if exists (select 1 from public.admins) then return false; end if;
  insert into public.admins(user_id) values (auth.uid());
  return true;
end $$;

revoke all on function public.claim_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;
grant execute on function public.has_admin() to anon, authenticated;
grant execute on function public.claim_admin() to authenticated;

-- ---------- permissions ----------
grant usage on schema public to anon, authenticated;
grant select on public.store to anon, authenticated;
grant insert, update on public.store to authenticated;
grant select, insert, update on public.profiles to authenticated;
grant insert on public.orders to anon, authenticated;
grant select, update, delete on public.orders to authenticated;

alter table public.store    enable row level security;
alter table public.admins   enable row level security;   -- kono policy nei: shudhu function-er maddhome
alter table public.profiles enable row level security;
alter table public.orders   enable row level security;

-- store: shobai pore, shudhu admin likhte pare
drop policy if exists "store public read"   on public.store;
drop policy if exists "store admin insert"  on public.store;
drop policy if exists "store admin update"  on public.store;
create policy "store public read"  on public.store for select to anon, authenticated using (true);
create policy "store admin insert" on public.store for insert to authenticated with check (public.is_admin());
create policy "store admin update" on public.store for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- profiles: customer nijer-ta, admin shob
drop policy if exists "profiles read"   on public.profiles;
drop policy if exists "profiles insert" on public.profiles;
drop policy if exists "profiles update" on public.profiles;
create policy "profiles read"   on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
create policy "profiles insert" on public.profiles for insert to authenticated with check (id = auth.uid());
create policy "profiles update" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

-- orders: je keu order dite pare; customer nijer order dekhe; admin shob dekhe o bodlay
drop policy if exists "orders insert"       on public.orders;
drop policy if exists "orders read"         on public.orders;
drop policy if exists "orders admin update" on public.orders;
drop policy if exists "orders admin delete" on public.orders;
create policy "orders insert" on public.orders for insert to anon, authenticated with check (
  public.is_admin() or (
    s = 'New' and (uid is null or uid = auth.uid())
    and coalesce(length(it), 0) < 6000 and coalesce(length(n), 0) < 200
  )
);
create policy "orders read"         on public.orders for select to authenticated using (public.is_admin() or uid = auth.uid());
create policy "orders admin update" on public.orders for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "orders admin delete" on public.orders for delete to authenticated using (public.is_admin());

-- ---------- photo storage ----------
insert into storage.buckets (id, name, public) values ('images', 'images', true) on conflict (id) do nothing;
drop policy if exists "images public read"   on storage.objects;
drop policy if exists "images admin insert"  on storage.objects;
drop policy if exists "images admin update"  on storage.objects;
drop policy if exists "images admin delete"  on storage.objects;
create policy "images public read"  on storage.objects for select using (bucket_id = 'images');
create policy "images admin insert" on storage.objects for insert to authenticated with check (bucket_id = 'images' and public.is_admin());
create policy "images admin update" on storage.objects for update to authenticated using (bucket_id = 'images' and public.is_admin()) with check (bucket_id = 'images' and public.is_admin());
create policy "images admin delete" on storage.objects for delete to authenticated using (bucket_id = 'images' and public.is_admin());
